CREATE TABLE node_instances (
    node_id      BIGINT PRIMARY KEY REFERENCES nodes(id) ON DELETE CASCADE,
    started_at   BIGINT NOT NULL DEFAULT 0,   -- Unix 秒,由 uptime 反推
    last_sync_at BIGINT NOT NULL DEFAULT 0,   -- Unix 秒
