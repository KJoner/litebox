    used_downlink  BIGINT NOT NULL DEFAULT 0,
    expires_at     TEXT,                          -- NULL 表示不过期
    reset_cycle    TEXT    NOT NULL DEFAULT 'NONE'
        CHECK (reset_cycle IN ('NONE','MONTHLY')),
    reset_day      BIGINT NOT NULL DEFAULT 1,    -- MONTHLY 时的重置日 1-28
    last_reset_at  TEXT,
    sub_token_hash TEXT    NOT NULL UNIQUE,       -- 订阅 Token 的 SHA-256
    created_at     TEXT    NOT NULL,
    updated_at     TEXT    NOT NULL,
    deleted_at     TEXT                            -- 软删除
, sub_token_encrypted TEXT NOT NULL DEFAULT '', sub_last_access_at TEXT, sub_last_access_ip TEXT NOT NULL DEFAULT '', sub_last_user_agent TEXT NOT NULL DEFAULT '', sub_access_count BIGINT NOT NULL DEFAULT 0, access_tier_id BIGINT NOT NULL DEFAULT 1, ss_password_encrypted TEXT NOT NULL DEFAULT '', mieru_password_encrypted TEXT NOT NULL DEFAULT '', snell_password_encrypted TEXT NOT NULL DEFAULT '');

