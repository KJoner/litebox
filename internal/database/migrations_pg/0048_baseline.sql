CREATE TABLE portal_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 一个代理用户最多一个登录账号。
    proxy_user_id BIGINT NOT NULL UNIQUE REFERENCES proxy_users(id) ON DELETE CASCADE,
    -- 登录账号与用户显示名称分离:显示名称允许重复、允许随时改,
    -- 而登录账号是凭据的一半,必须全局唯一且稳定。
    username      TEXT    NOT NULL UNIQUE,
    password_hash TEXT    NOT NULL,          -- argon2id,只存哈希
    -- login_enabled 是唯一能挡住门户登录的开关。
    -- 代理服务过期或超额的用户仍要能登录 —— 否则他连"为什么断了"都看不到,
    -- 只能来问管理员。
    login_enabled        BIGINT NOT NULL DEFAULT 1,
    must_change_password BIGINT NOT NULL DEFAULT 0,
    last_login_at        TEXT,
    last_login_ip        TEXT    NOT NULL DEFAULT '',
    created_at           TEXT    NOT NULL,
    updated_at           TEXT    NOT NULL
);

