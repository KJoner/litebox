CREATE TABLE user_nodes (
    proxy_user_id BIGINT NOT NULL REFERENCES proxy_users(id) ON DELETE CASCADE,
    node_id       BIGINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
    created_at    TEXT    NOT NULL,
