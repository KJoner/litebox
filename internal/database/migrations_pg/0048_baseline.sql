-- PostgreSQL 基线:与 SQLite 迁移 0001–0048 结束时的结构等价(VNext S2)。
--
-- 由 internal/database/pgbaseline_gen_test.go 从 SQLite 的最终结构翻译生成、人工核对后提交;
-- **应用后不可修改**,以后的结构变更在 migrations/ 与 migrations_pg/ 各加一个同版本号的迁移。
-- 各张表、各列的含义见 SQLite 那一侧的迁移注释与 docs/数据库说明.md。

CREATE TABLE admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      TEXT    NOT NULL UNIQUE,
    password_hash TEXT    NOT NULL,          -- argon2id
    created_at    TEXT    NOT NULL,
    updated_at    TEXT    NOT NULL,
    last_login_at TEXT
);

CREATE TABLE admin_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash    TEXT    NOT NULL UNIQUE,   -- 只存哈希,Cookie 里才是明文
    admin_user_id BIGINT NOT NULL REFERENCES admin_users(id) ON DELETE CASCADE,
    created_at    TEXT    NOT NULL,
    expires_at    TEXT    NOT NULL,
    last_seen_at  TEXT    NOT NULL,
    client_ip     TEXT    NOT NULL DEFAULT '',
    user_agent    TEXT    NOT NULL DEFAULT ''
);

CREATE TABLE login_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifier  TEXT NOT NULL,               -- 客户端 IP
    username    TEXT NOT NULL DEFAULT '',
    succeeded   BIGINT NOT NULL DEFAULT 0,
    attempted_at TEXT NOT NULL
);

CREATE TABLE proxy_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- user_code 是流量统计的唯一标识,格式 user_000001,一经分配不可变更。
