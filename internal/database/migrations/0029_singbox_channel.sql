-- sing-box 的版本通道(V14)。
--
-- Snell 是 sing-box 1.14 才有的入站,而 1.14 目前只有预览版
-- (v1.14.0-rc.1)。要用它就得在节点上换一个二进制,于是出现了
-- 「这台机器上跑的是哪一版」这个新问题。
--
-- ---------- 为什么是【节点级的一个通道】,而不是"两个版本并存" ----------
--
-- deployment.Layout 里的二进制路径(/opt/litebox/sing-box)、服务名
-- (litebox-singbox)、配置路径与备份目录全是**全局固定的一份**,
-- 而 V2Ray API 端口也是节点级的(一台机器上只有一个 sing-box 进程,
-- 也就只有一个 API 端点)。也就是说:
--
--     一台机器 = 一个节点 = 一个 sing-box 进程 = 一份 config.json
--
-- 「同时装两个」在这套布局里没有位置 —— 装第二个只会覆盖第一个。
-- 真要并存,得给第二个进程配一套服务定义、一份配置、一个 API 端口、
-- 一套配置状态/比对/回滚/巡检,以及 node_counters 里的第二个 source。
-- 换来的是什么?**什么都换不来** —— 预览版是正式版的超集,
-- 实测同一份 1.13 渲染出来的配置在 1.14 上 check 通过、真跑起来、
-- 零 deprecation 警告(V14 技术验证 §2)。愿意在这台机器上跑预览版的人,
-- 不会同时想在它旁边留一个正式版;不愿意的人则根本不该让预览版上机。
--
-- 所以版本是**一台机器一个**,这一列就是它。这台机器上全部 sing-box
-- 入口(VLESS、Shadowsocks、Snell)都跑在这一个二进制上 ——
-- 它们本来就在同一份 config.json 的同一个进程里,没有第二种可能。
--
-- ---------- 为什么它由【安装】写入,而不是一个独立的期望值 ----------
--
-- 与 protocol / ss_method 那一类不同,这一列描述的不是"我们希望怎样",
-- 而是**这台机器上那个文件是哪一版**。做成期望值就会多出一个
-- 「想要预览版、装的还是正式版」的中间态,而那个态没有任何界面能表达清楚:
-- 配置渲染要按哪一版来?渲染 snell 而机器上是正式版,
-- sing-box check 会在部署中途失败并回滚 —— 报错落在部署记录里,
-- 而管理员刚在入口表单上看到"已保存"。
--
-- 于是:切换通道 = 重新安装 + 下发配置(重启)。这正是它实际要做的事,
-- 界面上也就这么说,不再有第三个说法。
--
-- 存量节点一律 STABLE:它们上面装的确实是正式版。
ALTER TABLE nodes ADD COLUMN singbox_channel TEXT NOT NULL DEFAULT 'STABLE'
    CHECK (singbox_channel IN ('STABLE', 'PREVIEW'));
