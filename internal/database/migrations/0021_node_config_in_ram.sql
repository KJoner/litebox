-- 节点配置不落盘(V10)。
--
-- 中转主机上的 sing-box 配置里有两样东西:这台机器全部入口的用户凭据
-- (UUID / SS 密钥),以及它链出去的那条线路的落地地址与账号密码。
-- 那台机器往往是最便宜、最不受控的一台,而它手上的东西是最全的。
--
-- **这一列不是"启动后删配置"。** 那个做法挡不住它想挡的人:config.json
-- 是 0600,能读它的人本来就是 root,而 root 可以读 /proc/<pid>/mem、
-- 可以重启服务让面板把配置重新推上来。它挡得住的只有拿到磁盘的人 ——
-- 快照、镜像、商家手里那块退役硬盘 —— 而那恰恰是 tmpfs 挡得更彻底的。
--
-- 打开之后配置写在 /run/litebox 下(/run 在 systemd 与 OpenRC 上都是
-- 内存文件系统)。代价是明确的:机器重启后配置就没了,sing-box 起不来,
-- 要靠服务巡检重新下发把它救回来。所以这一项与「自动恢复」是配套的,
-- 单独打开它反而危险。
--
-- 默认 0:存量节点一个字不动。这是一个要管理员按机器决定的取舍,
-- 不是一个应该替他做的默认值。

ALTER TABLE nodes ADD COLUMN config_in_ram INTEGER NOT NULL DEFAULT 0;
